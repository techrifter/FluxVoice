package com.techrifter.fluxvoice.core.model

/**
 * Performance telemetry and resource accounting for a single conversational turn.
 * Emitted by the engine as soon as first audio playback begins and finalized when audio finishes.
 */
public data class TurnMetrics(
    /** Milliseconds elapsed from speech boundary detection to final STT transcript. */
    public val sttLatencyMs: Long = 0L,

    /** Milliseconds elapsed from final STT transcript to the first incoming LLM token. */
    public val timeToFirstTokenMs: Long = 0L,

    /** Milliseconds elapsed from final STT transcript to the start of audio playback. */
    public val timeToFirstAudioMs: Long = 0L,

    /** Total turn latency from user speech stop to final sentence audio playback completion. */
    public val totalTurnDurationMs: Long = 0L,

    /** Milliseconds from speech detection during playback to audio cancellation (if interrupted). */
    public val bargeInLatencyMs: Long? = null,

    /** Whether the user interrupted assistant playback during this turn. */
    public val bargeInOccurred: Boolean = false,

    /** Input prompt tokens consumed by this turn. */
    public val inputTokens: Int = 0,

    /** Output completion tokens generated by the LLM this turn. */
    public val outputTokens: Int = 0,

    /** True if token counts were calculated using word-count estimation rather than reported by API. */
    public val isTokensEstimated: Boolean = false,

    /** Estimated cost in USD for this turn based on provider pricing tables. */
    public val estimatedCostUsd: Double = 0.0
) {
    public val totalTokens: Int get() = inputTokens + outputTokens
    public val promptTokens: Int get() = inputTokens
    public val completionTokens: Int get() = outputTokens
    public val ttftMs: Long get() = timeToFirstTokenMs
    public val ttfaMs: Long get() = timeToFirstAudioMs
    public val totalTurnLatencyMs: Long get() = totalTurnDurationMs
}

